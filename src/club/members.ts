import type { Attr, Person } from '../boat/crewPhys';
import type { BoatSpec } from '../boat/spec';
import type { Settings } from '../settings';

/**
 * The Yacht Club's members (docs/YACHT-CLUB.md; the owner, 12 November 2026): the people who sail, as crew, skippers or
 * both, kept with your saves like your boats (store/cloud.ts copies every `fbsim-` key to your account). Your boat's crew
 * are members assigned to her seats (BoatSpec.crewIds: the middle crew, then the forward hand), and you are a member too:
 * her helm. The race's crew (Settings.crew, what the sim sails with) is drawn from her assignment (pullCrew), and the
 * setup's crew rows write back to the members (pushCrew), until the Yacht Club's own pages take over (phases 2 and 3).
 * The club's own members (generated by its sliders, phase 4) come later; for now the club boats sail as before.
 */
export type SkipperAttr = 'start' | 'speed' | 'strategy' | 'tactics' | 'rules' | 'consistency' | 'nerve';
export interface Member extends Person {
  id: string;
  /** Made up, never a real sailor's (ROADMAP). */
  name: string;
  /** What they sail as: crew, skipper, or both (a skipper who crews is rare in the club's generated roster). */
  roles: ('crew' | 'skipper')[];
  /** Yours (you made them, or brought from your old crew settings) or the club's (generated). */
  origin: 'yours' | 'club';
  /** The same person every race. */
  seed: number;
  /** As a skipper (ai/skipper.ts), each 0 … 1. */
  skipper?: Partial<Record<SkipperAttr, number>>;
}

/** You: the helm of your boat. */
export const YOU = 'you';
const KEY = 'fbsim-members';

export function loadMembers(): Member[] {
  try { const v = JSON.parse(localStorage.getItem(KEY) || '[]'); return Array.isArray(v) ? v.filter(isMember) : []; } catch { return []; }
}
export function saveMembers(ms: Member[]): void {
  try { localStorage.setItem(KEY, JSON.stringify(ms)); } catch { /* private mode etc. */ }
}
const isMember = (m: unknown): m is Member => !!m && typeof (m as Member).id === 'string' && typeof (m as Member).h === 'number' && typeof (m as Member).w === 'number';

/** A fixed number from a member's id (the seed: the same person every race). */
const seedOf = (id: string) => { let h = 2166136261; for (const ch of id) h = Math.imul(h ^ ch.charCodeAt(0), 16777619); return h >>> 0; };
const personOf = (p: Person): Person => ({ h: p.h, w: p.w, ...(p.skill != null ? { skill: p.skill } : {}), ...(p.attr ? { attr: { ...p.attr } } : {}) });

/** A new member of yours, as crew, from a person (height, weight, skill, attributes). */
export function newMember(ms: Member[], p: Person, name?: string): Member {
  let k = ms.filter(m => m.id.startsWith('crew-')).length + 1; while (ms.some(m => m.id === `crew-${k}`)) k++;
  const id = `crew-${k}`;
  const m: Member = { id, name: name ?? `Crew ${k}`, roles: ['crew'], origin: 'yours', seed: seedOf(id), ...personOf(p) };
  ms.push(m); return m;
}

/**
 * Once, from the old settings: you (the helm) and your crew become members, assigned to the boat you sail. Nothing is
 * lost: the heights, weights, skills and attributes you'd set carry over. Returns whether anything changed (to save).
 */
export function ensureMembers(s: Settings, ms: Member[]): boolean {
  let changed = false;
  if (!ms.some(m => m.id === YOU)) { ms.unshift({ id: YOU, name: 'You', roles: ['skipper', 'crew'], origin: 'yours', seed: seedOf(YOU), ...personOf(s.crew.helm) }); changed = true; }
  const boat = s.boats.find(b => b.id === s.boatId) ?? s.boat;
  if (boat && !boat.crewIds) {
    // (your crew as members: the ones you have already, or, the first time, from the old settings; your crew beyond the
    // count you'd chosen are still members, free for another day)
    const have = ms.filter(m => m.origin === 'yours' && m.id !== YOU).map(m => m.id);
    const ids = have.length ? have.slice(0, 2) : s.crew.people.slice(0, 2).map(p => newMember(ms, p).id);
    boat.crewIds = ids.slice(0, s.crew.n); changed = true;
  }
  return changed;
}

/** Your boat's crew for the race (Settings.crew) from her seats: you at the helm, then her middle crew and forward hand. */
export function pullCrew(s: Settings, ms: Member[]): void {
  const boat = s.boats.find(b => b.id === s.boatId) ?? s.boat, you = ms.find(m => m.id === YOU);
  if (!you || !boat) return;
  const crew = (boat.crewIds ?? []).map(id => ms.find(m => m.id === id)).filter((m): m is Member => !!m).slice(0, 2);
  // (the setup's crew count can add a second: the next of your members not aboard, or a club racer's build)
  const spare = ms.filter(m => m.origin === 'yours' && m.id !== YOU && !crew.includes(m));
  const people = [...crew, ...spare].slice(0, 2).map(personOf);
  while (people.length < 2) people.push({ h: 1.75, w: 75 });
  s.crew = { n: crew.length as 0 | 1 | 2, helm: personOf(you), people };
}

/** The setup's crew rows changed Settings.crew: write it back to the members, and your boat's seats to its count. */
export function pushCrew(s: Settings, ms: Member[]): void {
  const boat = s.boats.find(b => b.id === s.boatId) ?? s.boat, you = ms.find(m => m.id === YOU);
  if (!boat || !you) return;
  Object.assign(you, personOf(s.crew.helm)); if (!s.crew.helm.attr) delete you.attr;
  const ids = boat.crewIds ?? [], spare = ms.filter(m => m.origin === 'yours' && m.id !== YOU && !ids.includes(m.id));
  const seats: string[] = [];
  for (let i = 0; i < s.crew.n; i++) {
    const p = s.crew.people[i], m = ms.find(x => x.id === ids[i]) ?? spare.shift() ?? newMember(ms, p);
    Object.assign(m, personOf(p)); if (!p.attr) delete m.attr;
    seats.push(m.id);
  }
  boat.crewIds = seats;
}

/** The attributes a member can have as crew, for the cards (boat/crewPhys.ts Attr). */
export type { Attr };
/** A boat's crew seats, for its page (phase 3). */
export const seatsOf = (b: BoatSpec): string[] => b.crewIds ?? [];
